"""Research Planner for Question Decomposition and Strategy Formulation."""

import json
import logging
from typing import List, Optional
import requests
from pydantic import BaseModel, Field

from ..config import config

logger = logging.getLogger(__name__)

class ResearchPlan(BaseModel):
    """Structured decomposition of a research inquiry."""
    original_topic: str
    sub_questions: List[str] = Field(default_factory=list)
    reasoning: str = Field(default="")
    used_heuristic_fallback: bool = False

class ResearchPlanner:
    """Decomposes complex user inquiries into targeted, searchable sub-questions."""

    PLAN_PROMPT_TEMPLATE = """You are a senior research planning assistant.
Analyze this research topic and break it down into 2 to 3 concise, highly focused factual search questions.
Return ONLY valid JSON in the exact format shown below, with no explanation or extra text.

Format:
{{
  "reasoning": "Brief explanation of how the topic is broken down",
  "sub_questions": [
    "Targeted factual question 1",
    "Targeted factual question 2"
  ]
}}

Topic: {topic}
"""

    def __init__(self, base_url: Optional[str] = None, model_name: Optional[str] = None):
        self.base_url = (base_url or config.ollama_base_url).rstrip("/")
        self.model_name = model_name or config.ollama_model

    def plan(self, topic: str) -> ResearchPlan:
        """Create a targeted sub-question search plan using Ollama with heuristic fallback."""
        prompt = self.PLAN_PROMPT_TEMPLATE.format(topic=topic)
        payload = {
            "model": self.model_name,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.2,
                "num_ctx": 2048,
                "num_predict": config.max_planning_tokens,
            },
        }

        try:
            resp = requests.post(
                f"{self.base_url}/api/generate",
                json=payload,
                timeout=config.planner_timeout_seconds,
            )
            if resp.status_code == 200:
                text = resp.json().get("response", "").strip()
                start_idx = text.find("{")
                end_idx = text.rfind("}")
                if start_idx != -1 and end_idx != -1:
                    json_str = text[start_idx:end_idx + 1]
                    data = json.loads(json_str)
                    sub_qs = data.get("sub_questions", [])
                    if isinstance(sub_qs, list):
                        cleaned_sub_questions = [
                            question.strip()
                            for question in sub_qs
                            if isinstance(question, str) and question.strip()
                        ]
                        if cleaned_sub_questions:
                            return ResearchPlan(
                                original_topic=topic,
                                sub_questions=cleaned_sub_questions[:3],
                                reasoning=data.get(
                                    "reasoning", "Generated by research planner"
                                ),
                            )
            else:
                logger.warning("Ollama planner returned HTTP %s", resp.status_code)
        except (
            requests.exceptions.RequestException,
            ValueError,
            AttributeError,
            TypeError,
        ):
            logger.exception("Ollama planning failed; using a local heuristic fallback")

        # Fallback heuristic planning if LLM JSON parsing fails
        return ResearchPlan(
            original_topic=topic,
            sub_questions=[
                topic,
                f"Key principles and definitions related to {topic}",
                f"Findings, data, or results concerning {topic}"
            ],
            reasoning="Heuristic fallback plan",
            used_heuristic_fallback=True,
        )
